@dataclass(frozen=True)
class FileWrite:
    path: str
    content: str


@dataclass(frozen=True)
class FileDiff:
    path: str
    expected: str
    actual: str


@dataclass
class AdoptInput:
    engine_version: str
    ticket_files: dict[str, str]           # rel-path -> content
    skill_files: dict[str, str]            # rel-path -> content (old skill files)
    tests_first_content: str | None        # existing scripts/check_tests_first.py or None
    canonical_tests_first_content: str     # engine's canonical version
    agents_md_content: str | None          # existing AGENTS.md or None
    engine_config_content: str | None      # existing .ticket-engine.toml or None
    dispatch_workflow_content: str | None  # existing .github/workflows/dispatch.yml or None
    integrity_workflow_content: str | None
    ticket_template_content: str | None    # existing .github/ISSUE_TEMPLATE/ticket.md or None
    public_files: dict[str, str]           # rel-path -> content for PII scan


@dataclass
class AdoptResult:
    writes: list[FileWrite] = field(default_factory=list)
    diffs: list[FileDiff] = field(default_factory=list)
    pii_findings: list[PiiFinding] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)


# ---------------------------------------------------------------------------
# Pure adopt core helpers
# ---------------------------------------------------------------------------

def _handle_template_file(
    path: str,
    expected: str,
    existing: str | None,
    result: AdoptResult,
) -> None:
    """Add-if-absent / diff-if-edited policy for template files."""
    if existing is None:
        result.writes.append(FileWrite(path=path, content=expected))
    elif existing == expected:
        result.unchanged.append(path)
    else:
        result.diffs.append(FileDiff(path=path, expected=expected, actual=existing))


def _handle_agents_md(
    agents_md_content: str | None,
    result: AdoptResult,
) -> None:
    """Append implementation-protocol and roles-not-people sections to AGENTS.md.

    Uses string containment to check whether canonical sections are already
    present. If both are present verbatim, the file is unchanged. If both
    markers are present but the canonical section text differs, we diff and
    report without overwriting. If markers are absent, we append the sections.
    """
    impl_section = AGENTS_MD_IMPLEMENTATION_SECTION
    roles_section = AGENTS_MD_ROLES_SECTION

    if agents_md_content is None:
        new_content = "# AGENTS.md\n\n" + impl_section + "\n" + roles_section
        result.writes.append(FileWrite(path="AGENTS.md", content=new_content))
        return

    has_impl_marker = AGENTS_MD_IMPLEMENTATION_MARKER in agents_md_content
    has_roles_marker = AGENTS_MD_ROLES_MARKER in agents_md_content

    if has_impl_marker and has_roles_marker:
        if impl_section in agents_md_content and roles_section in agents_md_content:
            result.unchanged.append("AGENTS.md")
        else:
            # Developer edited our sections; compute expected and report diff.
            # Find the start of the impl section (the ## heading before the marker).
            impl_idx = agents_md_content.find(AGENTS_MD_IMPLEMENTATION_MARKER)
            heading_pos = agents_md_content.rfind("\n## ", 0, impl_idx)
            if heading_pos != -1:
                before = agents_md_content[: heading_pos + 1]
            else:
                before = agents_md_content[: impl_idx]
            expected_md = before + impl_section + "\n" + roles_section
            result.diffs.append(FileDiff(path="AGENTS.md", expected=expected_md, actual=agents_md_content))
        return

    # One or both sections absent: append missing ones.
    new_content = agents_md_content.rstrip("\n") + "\n"
    if not has_impl_marker:
        new_content += "\n" + impl_section
    if not has_roles_marker:
        new_content += "\n" + roles_section

    result.writes.append(FileWrite(path="AGENTS.md", content=new_content))


# ---------------------------------------------------------------------------
# Pure adopt core
# ---------------------------------------------------------------------------

def adopt(inp: AdoptInput) -> AdoptResult:
    """Pure bootstrap adopt core.

    Accepts all relevant file contents as input; returns FileWrite, FileDiff
    and PiiFinding lists. Performs no I/O.
    """
    result = AdoptResult()

    # --- Criterion 1: migrate ticket files ---
    for path, content in inp.ticket_files.items():
        migrated = migrate_ticket_text(content)
        if migrated != content:
            result.writes.append(FileWrite(path=path, content=migrated))
        else:
            result.unchanged.append(path)

    # --- Criterion 2a: replace skill files with pointer ---
    for path, content in inp.skill_files.items():
        if content == TICKET_SKILL_POINTER:
            result.unchanged.append(path)
        else:
            result.writes.append(FileWrite(path=path, content=TICKET_SKILL_POINTER))

    # --- Criterion 2b: replace tests-first script ---
    expected_tf = inp.canonical_tests_first_content
    if inp.tests_first_content is None:
        result.writes.append(FileWrite(path="scripts/check_tests_first.py", content=expected_tf))
    elif inp.tests_first_content == expected_tf:
        result.unchanged.append("scripts/check_tests_first.py")
    else:
        result.writes.append(FileWrite(path="scripts/check_tests_first.py", content=expected_tf))

    # --- Criterion 3a: engine config ---
    _handle_template_file(
        ".ticket-engine.toml",
        ENGINE_CONFIG_TEMPLATE,
        inp.engine_config_content,
        result,
    )

    # --- Criterion 3b: caller workflows ---
    _handle_template_file(
        ".github/workflows/dispatch.yml",
        caller_dispatch_workflow(inp.engine_version),
        inp.dispatch_workflow_content,
        result,
    )
    _handle_template_file(
        ".github/workflows/integrity.yml",
        caller_integrity_workflow(inp.engine_version),
        inp.integrity_workflow_content,
        result,
    )

    # --- Criterion 3c: ticket template ---
    _handle_template_file(
        ".github/ISSUE_TEMPLATE/ticket.md",
        TICKET_TEMPLATE,
        inp.ticket_template_content,
        result,
    )

    # --- Criterion 3d: AGENTS.md sections ---
    _handle_agents_md(inp.agents_md_content, result)

    # --- Criterion 4: PII scan ---
    result.pii_findings = scan_pii(inp.public_files)

    return result


