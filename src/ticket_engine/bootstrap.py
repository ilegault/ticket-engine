def _read_optional(path: pathlib.Path) -> str | None:
    """Read a file if it exists; return None otherwise."""
    return path.read_text(encoding="utf-8") if path.is_file() else None


def _collect_ticket_files(repo_dir: pathlib.Path) -> dict[str, str]:
    files: dict[str, str] = {}
    scratch = repo_dir / ".scratch"
    if scratch.is_dir():
        for p in scratch.rglob("*.md"):
            if p.is_file() and "issues" in p.parts:
                rel = p.relative_to(repo_dir).as_posix()
                files[rel] = p.read_text(encoding="utf-8")
    return files


def _collect_skill_files(repo_dir: pathlib.Path) -> dict[str, str]:
    """Find old skill files under .agents/skills/ or .claude/skills/."""
    files: dict[str, str] = {}
    for skills_root in (repo_dir / ".agents" / "skills", repo_dir / ".claude" / "skills"):
        if skills_root.is_dir():
            for p in skills_root.rglob("SKILL.md"):
                if p.is_file():
                    rel = p.relative_to(repo_dir).as_posix()
                    files[rel] = p.read_text(encoding="utf-8")
    return files


def _collect_public_files(repo_dir: pathlib.Path) -> dict[str, str]:
    """Collect public text source files for PII scanning.

    Excludes secrets files (.env), build/dist artifacts, binaries and archives.
    Only files that could reasonably end up in a public git repo as readable
    source are scanned.
    """
    skip_dirs = {".git", ".venv", "__pycache__", "node_modules", "dist", "build"}
    skip_extensions = {
        ".pyc", ".pyo", ".so", ".dll", ".exe", ".bin",
        ".png", ".jpg", ".jpeg", ".gif", ".svg", ".ico",
        ".woff", ".ttf", ".woff2", ".eot",
        ".zip", ".pyz", ".pkg", ".pyd", ".pem", ".crt", ".key",
    }
    files: dict[str, str] = {}
    for p in repo_dir.rglob("*"):
        if not p.is_file():
            continue
        if any(part in skip_dirs for part in p.parts):
            continue
        if p.suffix in skip_extensions:
            continue
        # Skip .env files (secrets files, never public source)
        if p.name == ".env" or p.name.startswith(".env."):
            continue
        try:
            rel = p.relative_to(repo_dir).as_posix()
            content = p.read_text(encoding="utf-8", errors="ignore")
            files[rel] = content
        except OSError:
            continue
    return files


def run_adopt(
    repo_dir: pathlib.Path | str,
    engine_version: str = "v0.1.0",
    canonical_tests_first_content: str | None = None,
) -> AdoptResult:
    """Adapter: read the repo, run the adopt core, write results to disk.

    Returns the AdoptResult for callers (e.g., tests) to inspect.
    """
    repo = pathlib.Path(repo_dir)

    if canonical_tests_first_content is None:
        engine_script = (
            pathlib.Path(__file__).parent.parent.parent / "scripts" / "check_tests_first.py"
        )
        canonical_tests_first_content = (
            engine_script.read_text(encoding="utf-8") if engine_script.is_file() else ""
        )

    inp = AdoptInput(
        engine_version=engine_version,
        ticket_files=_collect_ticket_files(repo),
        skill_files=_collect_skill_files(repo),
        tests_first_content=_read_optional(repo / "scripts" / "check_tests_first.py"),
        canonical_tests_first_content=canonical_tests_first_content,
        agents_md_content=_read_optional(repo / "AGENTS.md"),
        engine_config_content=_read_optional(repo / ".ticket-engine.toml"),
        dispatch_workflow_content=_read_optional(
            repo / ".github" / "workflows" / "dispatch.yml"
        ),
        integrity_workflow_content=_read_optional(
            repo / ".github" / "workflows" / "integrity.yml"
        ),
        ticket_template_content=_read_optional(
            repo / ".github" / "ISSUE_TEMPLATE" / "ticket.md"
        ),
        public_files=_collect_public_files(repo),
        repo_name=repo.name,
        planner_instructions_content=_read_optional(
            repo / ".agents" / "planner" / "INSTRUCTIONS.md"
        ),
    )

    result = adopt(inp)

    for fw in result.writes:
        target = repo / fw.path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(fw.content, encoding="utf-8")

    for diff in result.diffs:
        logger.warning(
            "bootstrap adopt: developer-edited file not overwritten: %s\n%s",
            diff.path,
            "".join(
                difflib.unified_diff(
                    diff.expected.splitlines(keepends=True),
                    diff.actual.splitlines(keepends=True),
                    fromfile=f"{diff.path} (expected)",
                    tofile=f"{diff.path} (actual)",
                )
            ),
        )

    return result


