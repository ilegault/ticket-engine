# Pure adopt core
# ---------------------------------------------------------------------------

def adopt(inp: AdoptInput) -> AdoptResult:
    """Pure bootstrap adopt core.

    Accepts all relevant file contents as input; returns FileWrite, FileDiff
    and PiiFinding lists. Performs no I/O.
    """
    result = AdoptResult()

    # --- Criterion 1: migrate ticket files ---
    for path, content in inp.ticket_files.items():
        migrated = migrate_ticket_text(content)
        if migrated != content:
            result.writes.append(FileWrite(path=path, content=migrated))
        else:
            result.unchanged.append(path)

    # --- Criterion 2a: replace skill files with pointer ---
    for path, content in inp.skill_files.items():
        if content == TICKET_SKILL_POINTER:
            result.unchanged.append(path)
        else:
            result.writes.append(FileWrite(path=path, content=TICKET_SKILL_POINTER))

    # --- Criterion 2b: replace tests-first script ---
    expected_tf = inp.canonical_tests_first_content
    if inp.tests_first_content is None:
        result.writes.append(FileWrite(path="scripts/check_tests_first.py", content=expected_tf))
    elif inp.tests_first_content == expected_tf:
        result.unchanged.append("scripts/check_tests_first.py")
    else:
        result.writes.append(FileWrite(path="scripts/check_tests_first.py", content=expected_tf))

    # --- Criterion 3a: engine config ---
    _handle_template_file(
        ".ticket-engine.toml",
        ENGINE_CONFIG_TEMPLATE,
        inp.engine_config_content,
        result,
    )

    # --- Criterion 3b: caller workflows ---
    _handle_template_file(
        ".github/workflows/dispatch.yml",
        caller_dispatch_workflow(inp.engine_version),
        inp.dispatch_workflow_content,
        result,
    )
    _handle_template_file(
        ".github/workflows/integrity.yml",
        caller_integrity_workflow(inp.engine_version),
        inp.integrity_workflow_content,
        result,
    )

    # --- Criterion 3c: ticket template ---
    _handle_template_file(
        ".github/ISSUE_TEMPLATE/ticket.md",
        TICKET_TEMPLATE,
        inp.ticket_template_content,
        result,
    )

    # --- Criterion 3d: AGENTS.md sections ---
    _handle_agents_md(inp.agents_md_content, result)

    # --- Criterion 3e: planner instructions ---
    if inp.repo_name:
        _handle_planner_instructions(inp.repo_name, inp.planner_instructions_content, result)

    # --- Criterion 4: PII scan ---
    result.pii_findings = scan_pii(inp.public_files)

    return result


