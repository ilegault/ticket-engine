"""Bootstrap adopt mode — file side.

WHY THIS EXISTS
---------------
Phase 1 Spec §Bootstrap and User Stories 51-60 require a bootstrap skill that
wires any existing repo to the engine. The `adopt` mode migrates legacy ticket
statuses, replaces the repo-specific ticket skill and tests-first script with
engine-canonical versions, adds the engine config, caller workflows, ticket
template and AGENTS.md sections, and scans public files for PII to report.

This module is the pure core: it accepts all relevant file contents as input
and returns a list of file writes, diffs and PII findings. No file I/O is done
here. The `run_adopt` adapter reads the repo, calls this core, and writes the
results to disk.

ADR references: ADR 0001 (tests-first, gate scripts), ADR 0002 (no real names
or IDs in public files, denylist enforcement).
"""
from __future__ import annotations

import difflib
import logging
import pathlib
import re
from dataclasses import dataclass, field

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Status migration
# ---------------------------------------------------------------------------

LEGACY_STATUS_MAP: dict[str, str] = {
    "complete": "done",
    "completed": "done",
    "human-task": "ready-for-developer",
}

# Matches both bold (**Status:** value) and plain (Status: value) forms.
_STATUS_LINE_RE = re.compile(
    r"^(\*\*Status:\*\*\s*|Status:\s*)(\S+)",
    re.MULTILINE | re.IGNORECASE,
)


def migrate_ticket_text(text: str) -> str:
    """Replace legacy status words with canonical ones.

    Handles both bold (**Status:** word) and plain (Status: word) forms.
    Only the status word itself is replaced; the rest of the line is unchanged.
    """
    def _replace(m: re.Match) -> str:
        prefix = m.group(1)
        word = m.group(2).strip().lower()
        canonical = LEGACY_STATUS_MAP.get(word)
        if canonical is not None:
            return prefix + canonical
        return m.group(0)

    return _STATUS_LINE_RE.sub(_replace, text)


